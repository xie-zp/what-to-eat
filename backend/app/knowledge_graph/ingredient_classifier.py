def classify_ingredient(name: str) -> str:
    """根据名称推断食材的大类，无法判断时归入其他。"""

    normalized = name.strip()
    for category, keywords in (
        ("工具", TOOL_KEYWORDS),
        ("调料", PROCESSED_KEYWORDS),
        ("调料", SEASONING_KEYWORDS),
        ("水产", AQUATIC_KEYWORDS),
        ("肉类", MEAT_KEYWORDS),
        ("蛋奶", EGG_DAIRY_KEYWORDS),
        ("豆制品", BEAN_KEYWORDS),
        ("主食", STAPLE_KEYWORDS),
        ("蔬菜", VEGETABLE_KEYWORDS),
        ("水果", FRUIT_KEYWORDS),
    ):
        if any(keyword in normalized for keyword in keywords):
            return category
    return "其他"
